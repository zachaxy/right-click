var stack = ClipboardStack()
stack.append("ignored")
assert(stack.ids.isEmpty)
stack.start()
stack.append("first")
stack.append("second")
stack.append("first")
assert(stack.ids == ["first", "second", "first"], "Repeated copies must remain in the paste queue")
stack.consume()
assert(stack.ids == ["second", "first"])
stack.reverse()
assert(stack.ids == ["first", "second"])
stack.discardMissing(["second"])
assert(stack.ids == ["second"], "Deleted history items cannot be pasted")
stack.consume(); stack.consume()
assert(stack.ids.isEmpty && stack.active)
stack.append("new")
stack.stop()
assert(stack.ids.isEmpty && !stack.active)
stack.start()
assert(stack.ids.isEmpty && stack.active)
print("Clipboard Stack ordering, duplicates, removal, restart: passed")
